// FALLBACK-RENDERER:
// Die Vitrine-Kacheln werden statisch via build.py ins HTML gebaut.
// Dieser Renderer hier ist Notnagel: wenn das statische Grid leer ist
// (z.B. weil jemand build.py vergessen hat), baut er die Kacheln
// zur Laufzeit nach. Er greift auf das DE-Felderpaar zu, weil er nur
// auf der deutschen vitrine.html laeuft (die englische en/vitrine.html
// laedt vitrine-en.js falls wir je einen JS-Fallback brauchen).
(function () {
  const grid = document.querySelector('[data-vitrine-grid]');
  if (!grid || !window.IAPPEAR_VITRINE) return;
  // Wenn das Grid bereits Kacheln hat (statisch gerendert), nicht anfassen.
  if (grid.querySelector('.vitrine-card')) return;
  const esc = s => (s || '').replace(/"/g, '&quot;');
  // Sprache aus <html lang>: 'en' -> englische Felder, sonst deutsche.
  const isEn = (document.documentElement.lang || 'de').startsWith('en');
  const langKey = isEn ? 'en' : 'de';
  const linkPrefix = isEn ? '../' : '';
  const ctaLabel = isEn ? '&ndash; read article &ndash;' : '&ndash; zum Artikel &ndash;';
  grid.innerHTML = window.IAPPEAR_VITRINE.map(item => {
    const loc = item[langKey] || item.de || {};
    const titel = loc.titel || '';
    const text = loc.text || '';
    const hasImg = !!item.bild;
    const imgSrc = hasImg ? (linkPrefix + item.bild) : '';
    const thumb = hasImg
      ? `<div class="vitrine-card__thumb"><img src="${esc(imgSrc)}" alt="${esc(titel)}" loading="lazy" decoding="async" /></div>`
      : `<div class="ph ph--square vitrine-card__thumb"><small>${esc(titel)}</small></div>`;
    return `
      <a class="vitrine-card" href="${esc(linkPrefix + item.link)}">
        ${thumb}
        <h3 class="vitrine-card__title">${titel}</h3>
        <p class="vitrine-card__text">${text}</p>
        <span class="vitrine-card__link">${ctaLabel}</span>
      </a>
    `;
  }).join('');
})();
